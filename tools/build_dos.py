#!/usr/bin/env python3
"""Build the native disk's ROM pieces: the DOS ROM and the HOME patches.

  tools/build_dos.py [--sjasmplus PATH]

Assembles dos/dos.asm twice (the DOS ROM, and HOME's side of the switch),
checks every HOME patch site against the stock ROM's bytes, and writes:

  dos/out/dos.rom        the 16K DOS ROM the emulator overlays on 0000h-3FFFh
  dos/out/home-dos.rom   the stock HOME ROM with the patches, for reference
  include/DosRom.h       both, for the firmware: it patches the HOME ROM it
                         loads from the card at boot, after checking the
                         same "before" bytes

The patch list is declarative, in the style of TS-Pico's build-rom.py: the
address, the stock bytes, the new bytes, and why.
"""

import argparse
import os
import subprocess
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOS = os.path.join(ROOT, "dos")
OUT = os.path.join(DOS, "out")
STOCK_HOME = os.path.join(ROOT, "patches", "base", "2068Home.BIN")
HEADER = os.path.join(ROOT, "include", "DosRom.h")

POCKET = 0x3CDC

# (address, stock bytes, new bytes, why). "POCKET" is filled in from the
# assembled HOME side of dos.asm.
HOME_PATCHES = [
    (0x1946, "d0", "d2",
     "CAT's syntax entry: skip the stock 0Ah 2Ch to class 05h, routine 25C8h, "
     "so a bare CAT parses (TS-Pico's hunk, CAT's byte only)"),
    (0x25C8, "06 cf 18 0a", "c3 dc 3c 00",
     "CAT's stub: LD B,CFh / JR 25D6h -> JP H_CAT (3CDCh), into the DOS ROM"),
    (POCKET, None, "POCKET",
     "the switch to the DOS ROM and back, in the genuine FFh filler before CHRSET"),
    # Anchors: HOME code the DOS ROM calls, unchanged, checked so a HOME ROM
    # where it has moved gets no native disk rather than a crash.
    (0x0010, "c3 ed 11", "c3 ed 11", "anchor: RST 10h, print A (H_PRINT_A)"),
    (0x0053, "e1 6e fd 75 00 ed 7b 3d 5c c3 54 13", "e1 6e fd 75 00 ed 7b 3d 5c c3 54 13",
     "anchor: RST 8's tail; 0055h raises the report in L (H_ERROR_3)"),
    (0x1230, "87 c6 16 6f 26 5c", "87 c6 16 6f 26 5c", "anchor: CHAN-OPEN (H_CHAN_OPEN)"),
    (0x1B44, "cd 89 28 c0 c1 c1 df fe 0d", "cd 89 28 c0 c1 c1 df fe 0d",
     "anchor: CHECK-END, then STMT-NEXT at 1B4Ah (H_CHECK_END)"),
]


def assemble(sjasm, side):
    cmd = [sjasm, "--nologo", "--msg=war", f"-DSIDE_HOME={side}", "dos.asm"]
    r = subprocess.run(cmd, cwd=DOS, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"sjasmplus failed (SIDE_HOME={side}):\n{r.stdout}{r.stderr}")


def c_bytes(data, indent="    ", per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sjasmplus", default=os.environ.get("SJASMPLUS", "sjasmplus"))
    args = ap.parse_args()

    os.makedirs(OUT, exist_ok=True)
    assemble(args.sjasmplus, 0)
    assemble(args.sjasmplus, 1)

    dos = open(os.path.join(OUT, "dos.rom"), "rb").read()
    pocket = open(os.path.join(OUT, "home_pocket.bin"), "rb").read()
    if len(dos) != 0x4000:
        sys.exit(f"dos.rom is {len(dos)} bytes, not 16K")
    if POCKET + len(pocket) > 0x3D00:
        sys.exit("HOME's pocket runs into CHRSET")

    stock = open(STOCK_HOME, "rb").read()
    if len(stock) != 0x4000:
        sys.exit("the stock HOME ROM is not 16K")
    home = bytearray(stock)
    patches = []
    for addr, before, after, why in HOME_PATCHES:
        new = pocket if after == "POCKET" else bytes.fromhex(after)
        old = bytes([0xFF]) * len(new) if before is None else bytes.fromhex(before)
        if len(old) != len(new):
            sys.exit(f"{addr:04X}h: before and after differ in length")
        if stock[addr:addr + len(old)] != old:
            sys.exit(f"{addr:04X}h: the stock ROM has {stock[addr:addr + len(old)].hex(' ')}, "
                     f"not {old.hex(' ')}")
        home[addr:addr + len(new)] = new
        patches.append((addr, old, new, why))
        print(f"  HOME {addr:04X}h  {len(new):3d} bytes  {why}")

    open(os.path.join(OUT, "home-dos.rom"), "wb").write(home)

    used = max(i for i, b in enumerate(dos[:POCKET]) if b != 0xFF) + 1
    print(f"  DOS ROM: module 0100h-{used - 1:04X}h ({used - 0x100} bytes), "
          f"CRC {zlib.crc32(dos):08x}")
    print(f"  HOME: stock CRC {zlib.crc32(stock):08x}, patched {zlib.crc32(home):08x}")

    out = []
    out.append("// Generated by tools/build_dos.py from dos/dos.asm. Do not edit.")
    out.append("//")
    out.append("// The native disk's ROM pieces: the HOME patches (checked against the")
    out.append("// stock bytes before they are applied) and the 16K DOS ROM the emulator")
    out.append("// overlays on 0000h-3FFFh while the module runs. See include/DiskEngine.h.")
    out.append("")
    out.append("#ifndef DosRom_h")
    out.append("#define DosRom_h")
    out.append("")
    out.append("#include <inttypes.h>")
    out.append("")
    out.append("namespace DosRom {")
    out.append("")
    out.append("struct Patch {")
    out.append("    uint16_t addr;")
    out.append("    uint16_t len;")
    out.append("    const uint8_t* before;")
    out.append("    const uint8_t* after;")
    out.append("};")
    out.append("")
    for i, (addr, old, new, why) in enumerate(patches):
        out.append(f"// {addr:04X}h: {why}")
        out.append(f"static const uint8_t patch{i}Before[] = {{")
        out.append(c_bytes(old))
        out.append("};")
        out.append(f"static const uint8_t patch{i}After[] = {{")
        out.append(c_bytes(new))
        out.append("};")
    out.append("")
    out.append("static const Patch homePatches[] = {")
    for i, (addr, old, new, why) in enumerate(patches):
        out.append(f"    {{ 0x{addr:04x}, {len(new)}, patch{i}Before, patch{i}After }},")
    out.append("};")
    out.append(f"static const int homePatchCount = {len(patches)};")
    out.append("")
    out.append(f"// The DOS ROM, 16K (CRC32 {zlib.crc32(dos):08x}).")
    out.append("static const uint8_t image[16384] = {")
    out.append(c_bytes(dos))
    out.append("};")
    out.append("")
    out.append("} // namespace DosRom")
    out.append("")
    out.append("#endif")
    open(HEADER, "w").write("\n".join(out) + "\n")
    print(f"  wrote {os.path.relpath(HEADER, ROOT)}")


if __name__ == "__main__":
    main()
