#!/usr/bin/env python3
"""Make bringup/font8x8.h from the character set in a TS2068 ROM.

The character set (96 characters, 8 bytes each, from space) is at 0x3D00 in
the HOME ROM, as on the Spectrum. The default ROM is the TS-Pico's
TSPICO-23.ROM (MIT, tspico-firmware-build).

    python3 tools/make_font.py [ROM] > bringup/font8x8.h
"""

import pathlib
import sys

DEFAULT = pathlib.Path.home() / "Documents/github/tspico-firmware-build/src/rom/TSPICO-23.ROM"


def main() -> None:
    rom_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    rom = rom_path.read_bytes()
    font = rom[0x3D00:0x3D00 + 96 * 8]
    print(f"// Generated by tools/make_font.py from {rom_path.name} (0x3D00, 96 characters).")
    print("// The TS-Pico ROM is MIT licensed (tspico-firmware-build).")
    print("#pragma once")
    print("#include <stdint.h>")
    print("static const uint8_t font8x8[96][8] = {")
    for c in range(96):
        rows = ", ".join(f"0x{b:02x}" for b in font[c * 8:c * 8 + 8])
        label = chr(c + 32) if chr(c + 32) not in "\\" else "backslash"
        print(f"    {{{rows}}},  // {label!r}")
    print("};")


if __name__ == "__main__":
    main()
